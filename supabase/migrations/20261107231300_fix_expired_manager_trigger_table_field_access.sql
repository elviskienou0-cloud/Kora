-- Avoid reading table-specific trigger fields before confirming the row's table.
-- This keeps expired-manager presence and payment-notification exceptions narrow.

CREATE OR REPLACE FUNCTION public.reject_expired_manager_writes()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  actor_id uuid;
  actor_role text;
BEGIN
  actor_id := auth.uid();

  -- Trusted server-side jobs and webhooks have no end-user JWT.
  IF actor_id IS NULL THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;

  actor_role := public.get_my_role();

  IF actor_role = 'manager'
     AND NOT public.is_admin()
     AND NOT public.manager_has_active_plan() THEN

    -- Check the table before referencing profile-only columns.
    IF TG_OP = 'UPDATE'
       AND TG_TABLE_SCHEMA = 'public'
       AND TG_TABLE_NAME = 'profiles' THEN
      IF OLD.id = actor_id
         AND NEW.id = actor_id
         AND NEW.last_seen IS DISTINCT FROM OLD.last_seen
         AND (to_jsonb(NEW) - 'last_seen' - 'updated_at')
             = (to_jsonb(OLD) - 'last_seen' - 'updated_at') THEN
        RETURN NEW;
      END IF;
    END IF;

    -- Check the table before referencing notification-only columns.
    IF TG_OP = 'INSERT'
       AND TG_TABLE_SCHEMA = 'public'
       AND TG_TABLE_NAME = 'notifications' THEN
      IF NEW.user_id = actor_id
         AND NEW.type = 'payment'
         AND NEW.data ->> 'status' = 'pending'
         AND EXISTS (
           SELECT 1
           FROM public.payments AS payment
           WHERE payment.id::text = NEW.data ->> 'payment_id'
             AND payment.user_id = actor_id
             AND payment.provider = 'saspay'
             AND payment.status = 'pending'
             AND payment.metadata ->> 'source' = 'kora_subscription'
         ) THEN
        RETURN NEW;
      END IF;
    END IF;

    RAISE EXCEPTION 'SUBSCRIPTION_EXPIRED: manager account is read-only until renewal'
      USING ERRCODE = '42501';
  END IF;

  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$function$;

COMMENT ON FUNCTION public.reject_expired_manager_writes() IS
  'Blocks business-data writes for expired managers while permitting only own-profile last_seen heartbeats and the payment notification generated by a real pending KORA SasPay subscription renewal. Table-specific NEW/OLD fields are accessed only after checking TG_TABLE_NAME.';
