-- Keep expired Manager accounts read-only without blocking technical presence
-- heartbeats or the narrow payment notification required to renew a plan.
--
-- This migration intentionally does not relax any business-data write guard.

CREATE OR REPLACE FUNCTION public.reject_expired_manager_writes()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  actor_id uuid;
  actor_role text;
BEGIN
  actor_id := auth.uid();

  -- Trusted server-side jobs and webhooks have no end-user JWT.
  IF actor_id IS NULL THEN
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END IF;

  actor_role := public.get_my_role();

  IF actor_role = 'manager'
     AND NOT public.is_admin()
     AND NOT public.manager_has_active_plan() THEN

    -- Allow only a heartbeat update on the manager's own profile.
    -- No identity, contact, role, suspension, preference, or other field
    -- can change in the same statement.
    IF TG_OP = 'UPDATE'
       AND TG_TABLE_SCHEMA = 'public'
       AND TG_TABLE_NAME = 'profiles'
       AND NEW.last_seen IS DISTINCT FROM OLD.last_seen
       AND (to_jsonb(NEW) - 'last_seen' - 'updated_at')
           = (to_jsonb(OLD) - 'last_seen' - 'updated_at') THEN
      RETURN NEW;
    END IF;

    -- A pending SasPay subscription payment must be able to create its own
    -- in-app payment notification. This exception is tied to a real pending
    -- payment owned by the current manager; it does not permit talent,
    -- profile, message, project, request, or arbitrary notification writes.
    IF TG_OP = 'INSERT'
       AND TG_TABLE_SCHEMA = 'public'
       AND TG_TABLE_NAME = 'notifications'
       AND NEW.user_id = actor_id
       AND NEW.type = 'payment'
       AND NEW.data ->> 'status' = 'pending'
       AND EXISTS (
         SELECT 1
         FROM public.payments AS payment
         WHERE payment.id::text = NEW.data ->> 'payment_id'
           AND payment.user_id = actor_id
           AND payment.provider = 'saspay'
           AND payment.status = 'pending'
           AND payment.metadata ->> 'source' = 'kora_subscription'
       ) THEN
      RETURN NEW;
    END IF;

    RAISE EXCEPTION 'SUBSCRIPTION_EXPIRED: manager account is read-only until renewal'
      USING ERRCODE = '42501';
  END IF;

  RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$function$;

COMMENT ON FUNCTION public.reject_expired_manager_writes() IS
  'Blocks business-data writes for expired managers while permitting only own-profile last_seen heartbeats and the payment notification generated by a real pending KORA SasPay subscription renewal.';
